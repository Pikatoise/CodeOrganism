export const isRussian = () => document.documentElement.lang === "ru";
export const t = (text: string) => isRussian() && Object.hasOwn(russian, text) ? russian[text] : text;
export const nodeLabel = (node: { kind: string; label: string }) =>
  node.kind === "library" || node.kind === "unresolved" ? t(node.label) : node.label;

const numbers = {
  en: new Intl.NumberFormat("en-US", { maximumFractionDigits: 1 }),
  ru: new Intl.NumberFormat("ru-RU", { maximumFractionDigits: 1 })
};
export const number = (value: number) => numbers[isRussian() ? "ru" : "en"].format(value);

export function localizeMarkup() {
  const staticText = [...document.querySelectorAll(
    "#settings-title, .settings-fields label, .settings-fields p, #graphics-quality option, #theme option, " +
    ".attach label, #attach, #detach, #map-title, .metrics button, #reset-view, #collapse-all, " +
    "#metric-caption, #metric-legend, #branch-legend, #map-empty, #attach-progress span:last-child, " +
    "#ranking-title, .ranking-scope label, #ranking-scope option, #ranking-control label, #rank-metric, " +
    "#inspector-title, #selection-name, #groups-title"
  )].map(element => [element, element.textContent ?? ""] as const);
  const labels = [...document.querySelectorAll("[aria-label]")]
    .map(element => [element, element.getAttribute("aria-label")!] as const);
  const tooltips = [...document.querySelectorAll("[title]")]
    .map(element => [element, element.getAttribute("title")!] as const);
  return () => {
    for (const [element, text] of staticText) element.textContent = t(text);
    for (const [element, text] of labels) element.setAttribute("aria-label", t(text));
    for (const [element, text] of tooltips) element.setAttribute("title", t(text));
  };
}
